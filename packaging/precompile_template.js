// Build step for the packaged app: compiles the page template ahead of time, so the app can run
// with Vue's runtime-only build and a Content Security Policy without 'unsafe-eval'.
//   node packaging/precompile_template.js <renderer dir in the app bundle>
// Rewrites index.html there (empty #app, runtime Vue, strict CSP) and writes app_render.js.
const fs = require("fs");
const path = require("path");

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node precompile_template.js <renderer dir>");
  process.exit(2);
}
const appDir = path.join(__dirname, "..", "app");
const { parse, compile } = require(require.resolve("@vue/compiler-dom", { paths: [path.join(appDir, "node_modules/vue")] }));

const htmlPath = path.join(dir, "index.html");
const html = fs.readFileSync(htmlPath, "utf8");

// locate <div id="app" ...> ... </div> with the compiler's own parser (exact offsets)
const ast = parse(html, { comments: false });
let appEl = null;
(function walk(nodes) {
  for (const n of nodes || []) {
    if (appEl) return;
    if (n.type === 1 && n.tag === "div" && (n.props || []).some((p) => p.type === 6 && p.name === "id" && p.value && p.value.content === "app")) {
      appEl = n;
      return;
    }
    walk(n.children);
  }
})(ast.children);
if (!appEl || !appEl.children.length) {
  console.error("couldn't find <div id=\"app\"> in index.html");
  process.exit(1);
}
const start = appEl.children[0].loc.start.offset;
const end = appEl.children[appEl.children.length - 1].loc.end.offset;
const template = html.slice(start, end);

const errors = [];
const { code } = compile(template, {
  mode: "function",
  hoistStatic: true,
  onError: (e) => errors.push(e),
  onWarn: () => {},
});
const fatal = errors.filter((e) => !/side effect/i.test(e.message));
if (fatal.length) {
  console.error("template errors:\n" + fatal.map((e) => "  " + e.message).join("\n"));
  process.exit(1);
}
fs.writeFileSync(path.join(dir, "app_render.js"),
  "// Generated by packaging/precompile_template.js. Do not edit.\n" +
  "window.__PROTOART_RENDER__ = (function () {\n" + code + "\n})();\n");

let out = html.slice(0, start) + html.slice(end);
out = out.replace(/script-src 'self' 'unsafe-eval'/, "script-src 'self'");
if (/unsafe-eval/.test(out)) {
  console.error("couldn't tighten the Content Security Policy");
  process.exit(1);
}
out = out.replace("../node_modules/vue/dist/vue.global.prod.js", "../node_modules/vue/dist/vue.runtime.global.prod.js");
out = out.replace('<script src="app.js"></script>', '<script src="app_render.js"></script>\n<script src="app.js"></script>');
if (!out.includes("vue.runtime.global.prod.js") || !out.includes("app_render.js")) {
  console.error("couldn't rewrite the script tags in index.html");
  process.exit(1);
}
fs.writeFileSync(htmlPath, out);
console.log(`precompiled template (${(code.length / 1024).toFixed(0)} KB), CSP without unsafe-eval`);
